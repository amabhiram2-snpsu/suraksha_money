/**
 * Get translation for given key and language code, with fallback to Hindi then English.
 */
export function t(key: string, lang: LanguageCode = 'en'): string {
  const item = TRANSLATIONS[key];
  if (!item) return key;

  if (item[lang]) return item[lang];
  if (item['en']) return item['en'];
  return key;
}
